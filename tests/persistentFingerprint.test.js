const test = require("node:test")
const assert = require("node:assert/strict")
const fs = require("node:fs/promises")
const path = require("node:path")
const { DatabaseSync } = require("node:sqlite")
const { fingerprint, preserved } = require("../ops/persistent-fingerprint")

test("deployment fingerprint permits only additive defaults while preserving all previous rows, uploads and authentication", async context => {
  const root = await fs.mkdtemp("/tmp/llm-canvas-fingerprint-")
  context.after(() => fs.rm(root, { recursive: true, force: true }))
  const prisma = path.join(root, "prisma")
  const uploads = path.join(root, "uploads")
  await fs.mkdir(prisma)
  await fs.mkdir(uploads)
  await fs.writeFile(path.join(prisma, ".auth.secret"), "synthetic-test-secret")
  await fs.writeFile(path.join(uploads, "fixture.png"), "fixture bytes")
  const database = new DatabaseSync(path.join(prisma, "dev.db"))
  database.exec("CREATE TABLE users(id TEXT PRIMARY KEY, email TEXT); CREATE TABLE token_usage(id TEXT PRIMARY KEY, totalTokens INTEGER); INSERT INTO users VALUES ('owner','fixture@example.invalid'); INSERT INTO token_usage VALUES ('usage',170);")
  const before = await fingerprint(prisma, uploads)
  database.exec("ALTER TABLE users ADD COLUMN authVersion INTEGER NOT NULL DEFAULT 0; ALTER TABLE token_usage ADD COLUMN usageSource TEXT;")
  const after = await fingerprint(prisma, uploads)
  assert.notEqual(before.database, after.database)
  assert.ok(preserved(before, after))
  database.exec("UPDATE token_usage SET totalTokens = 171")
  assert.equal(preserved(before, await fingerprint(prisma, uploads)), false)
  database.exec("UPDATE token_usage SET totalTokens = 170; UPDATE users SET authVersion = 1")
  assert.equal(preserved(before, await fingerprint(prisma, uploads)), false)
  database.close()
  await fs.writeFile(path.join(prisma, ".auth.secret"), "changed")
  assert.equal(preserved(after, await fingerprint(prisma, uploads)), false)
})
