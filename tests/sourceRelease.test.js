const test = require("node:test")
const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")
const os = require("node:os")
const { execFileSync } = require("node:child_process")
const { sourceRelease, publishable } = require("../ops/source-release")

function fixture(context) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "llm-canvas-release-test-"))
  context.after(() => fs.rmSync(root, { recursive: true, force: true }))
  const repository = path.join(root, "repo")
  fs.mkdirSync(repository)
  const git = args => execFileSync("git", ["-c", "user.name=Fixture", "-c", "user.email=fixture@test.invalid", "-c", "commit.gpgsign=false", ...args], { cwd: repository, stdio: ["ignore", "pipe", "pipe"] })
  const put = (name, data) => { const filename = path.join(repository, name); fs.mkdirSync(path.dirname(filename), { recursive: true }); fs.writeFileSync(filename, data) }
  git(["init", "-q"])
  put("package.json", '{"name":"fixture","version":"0.1.0-rc.1"}')
  put("README.md", "Public documentation")
  put("docs/images/canvas-demo.png", Buffer.from([137, 80, 78, 71, 0]))
  put("docs/images/private.png", "PRIVATE_UNREVIEWED_IMAGE")
  put("screenshots/00_dark_canvas.png", "PRIVATE_HISTORIC_SCREENSHOT")
  put("src/index.ts", "export const value = 1")
  put("src/app/api/canvases/route.ts", "export const POST = () => true")
  put("src/app/api/canvases/[id]/route.ts", "export const GET = () => true")
  put("src/app/api/canvas/[id]/route.ts", "export const GET = () => true")
  put("public/canvases/old/user.png", "PRIVATE_USER_IMAGE")
  git(["add", "."]); git(["commit", "-qm", "old user image"])
  git(["rm", "-q", "public/canvases/old/user.png"])
  put("docker.env", "PRIVATE_RUNTIME_SETTINGS")
  put(".env.example", "AUTH_SECRET=")
  put("REPORT-private.md", "PRIVATE_INSTALLATION_REPORT")
  put("prisma/dev.db", "PRIVATE_DATABASE")
  put("public/uploads/current.png", "PRIVATE_CURRENT_IMAGE")
  git(["add", "."]); git(["commit", "-qm", "release source"])
  return { root, repository, git, put }
}

test("source release excludes history, tracked runtime data and operational reports; output is reproducible", context => {
  const state = fixture(context)
  const first = sourceRelease(path.join(state.root, "first"), "HEAD", state.repository)
  const second = sourceRelease(path.join(state.root, "second"), "HEAD", state.repository)
  assert.equal(first.sha256, second.sha256)
  const archive = path.join(state.root, "first", first.archive)
  const listing = execFileSync("tar", ["-tzf", archive], { encoding: "utf8" })
  assert.ok(listing.includes("src/index.ts") && listing.includes(".env.example"))
  assert.ok(listing.includes("docs/images/canvas-demo.png"))
  assert.ok(!listing.includes("docs/images/private.png") && !listing.includes("screenshots/00_dark_canvas.png"))
  assert.ok(!/docker\.env|dev\.db|public\/(?:uploads|canvases)|REPORT-private|\.git\//.test(listing))
  for (const filename of ["src/app/api/canvases/route.ts", "src/app/api/canvases/[id]/route.ts", "src/app/api/canvas/[id]/route.ts"]) assert.ok(listing.includes(filename), "legitimate API files, including literal bracket routes, must survive privacy filtering")
  const extracted = path.join(state.root, "extracted")
  fs.mkdirSync(extracted)
  execFileSync("tar", ["-xzf", archive, "-C", extracted])
  assert.equal(fs.readFileSync(path.join(extracted, "llm-canvas-0.1.0-rc.1/src/index.ts"), "utf8"), "export const value = 1")
  assert.equal(first.containsGitHistory, false)
  assert.equal(first.privateRuntimePathsIncluded, false)
  assert.equal(fs.statSync(archive).mode & 0o777, 0o600)
})

test("source release refuses symlinks instead of following private filesystem paths", context => {
  const state = fixture(context)
  fs.symlinkSync("/private/unrelated", path.join(state.repository, "src/link"))
  state.git(["add", "src/link"]); state.git(["commit", "-qm", "unsafe link"])
  assert.throws(() => sourceRelease(path.join(state.root, "output"), "HEAD", state.repository), /must not contain links/)
})


test("native source acquisition, verification and rebuild materials accompany public source", () => {
  for (const filename of ["ops/native-source-materials.py", "ops/native-source-pins.json", "docs/NATIVE-SOURCE-MATERIALS.md", "docs/RELEASE-VERIFICATION.md"]) assert.equal(publishable(filename), true, filename)
  for (const filename of ["REPORT-phase32.md", "REPORT-phase33.md", "AGENTS.md", "KICKOFF.md", "ops/promote-artifact.js", "docker.env", "public/canvases/private.png"]) assert.equal(publishable(filename), false, filename)
})
